/** Legacy id aliases so old skill rows still resolve. */
const LEGACY_IDS: Record<string, string> = {
  negative: "present-continuous-negation",
  question: "present-continuous-questions",
  possessive: "possessive-suffixes",
  "neg-ability": "inability",
  conditional: "basic-conditional",
  participles: "basic-participles",
  passive: "basic-passive",
  causative: "basic-causative",
  "time-expressions": "time-expressions-a1",
}

export function structuresByCefr(level?: CefrLevel | "all") {
  if (!level || level === "all") return GRAMMAR_STRUCTURES
  const order = ["A1", "A2", "B1", "B2", "C1", "C2"]
  const max = order.indexOf(level)
  return GRAMMAR_STRUCTURES.filter((item) => order.indexOf(item.cefr) <= max)
}

export function structuresForExactLevel(level: CefrLevel) {
  return GRAMMAR_STRUCTURES.filter((item) => item.cefr === level)
}

export function getStructure(id: string) {
  const resolved = LEGACY_IDS[id] ?? id
  return GRAMMAR_STRUCTURES.find((item) => item.id === resolved) ?? null
}

export function grammarLevelsPresent(): CefrLevel[] {
  return (["A1", "A2", "B1", "B2", "C1", "C2"] as CefrLevel[]).filter((level) =>
    GRAMMAR_STRUCTURES.some((item) => item.cefr === level),
  )
}

export function grammarPromptBlock(knownIds: string[], introduceNew: boolean): string {
  const known = GRAMMAR_STRUCTURES.filter((item) => knownIds.includes(item.id) || knownIds.some((id) => LEGACY_IDS[id] === item.id))
  const unknown = GRAMMAR_STRUCTURES.filter((item) => !known.some((k) => k.id === item.id))
  const knownList = known.length
    ? known
        .slice(0, 40)
        .map((item) => `- ${item.label} (${item.example})`)
        .join("\n")
    : "- Keep grammar extremely simple (present tense, basic word order)."
  const instruction = introduceNew && unknown[0]
    ? `You may introduce exactly one new structure: ${unknown[0].label}. Explain it briefly in English after the Turkish text.`
    : "Do not introduce unfamiliar grammar structures. Stay within the known list."

  return `Known grammar:\n${knownList}\n\n${instruction}`
}

