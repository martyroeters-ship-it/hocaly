import type { CefrLevel } from "@/lib/types"

export type GrammarCategory = "verb" | "case" | "noun" | "sentence" | "particle" | "other"

export type GrammarStructure = {
  id: string
  label: string
  example: string
  hint: string
  cefr: CefrLevel
  category: GrammarCategory
  section: string
  /** Can generate full person paradigms from a verb stem */
  conjugable: boolean
  /** Short English why/when usage tip (shown under the topic subtitle) */
  focusTip: string
  /** Static browse examples (used when not conjugable, or as extras) */
  examples: { verb: string; english: string; forms: { label: string; turkish: string }[] }[]
}

function s(
  partial: Omit<GrammarStructure, "examples" | "conjugable" | "focusTip" | "category" | "section"> &
    Partial<Pick<GrammarStructure, "examples" | "conjugable" | "focusTip" | "category" | "section">>,
): GrammarStructure {
  return {
    category: "other",
    section: "General",
    conjugable: false,
    focusTip: partial.hint,
    examples: [],
    ...partial,
  }
}

